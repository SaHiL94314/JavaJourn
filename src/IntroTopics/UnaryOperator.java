package IntroTopics;

public class UnaryOperator {
    public static void main(String[] args) {
        int a=12,b=12;

        int res1=++a;
        System.out.println(res1);
        int res2=--b;
        System.out.println(res2);
        System.out.println("a value is "+a);
        System.out.println("b value is "+b);
    }
}
